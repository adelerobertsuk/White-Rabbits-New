import Foundation

enum Affirmations {
    private static let epoch: Date = {
        var components = DateComponents()
        components.year = 2025
        components.month = 1
        components.day = 1
        return Calendar.current.date(from: components) ?? Date(timeIntervalSince1970: 0)
    }()

    static func line(for date: Date = Date()) -> String {
        let calendar = Calendar.current
        let startOfDay = calendar.startOfDay(for: date)
        let startOfEpoch = calendar.startOfDay(for: epoch)
        let daysSinceEpoch = calendar.dateComponents([.day], from: startOfEpoch, to: startOfDay).day ?? 0
        let index = ((daysSinceEpoch % all.count) + all.count) % all.count
        return all[index]
    }

    /// The day's line before any personal intention is layered on top: the
    /// ritual greeting on the 1st, the affirmation-of-the-day otherwise. Used
    /// by the widget extension, which has no access to the app's saved data.
    static func dailyLine(for date: Date = Date()) -> String {
        dailyLine(for: date, greetingDue: Calendar.current.component(.day, from: date) == 1, intention: "")
    }

    /// The single rule for "the line of the day", shared by Home, the 11:11
    /// notifications (iPhone, and Apple Watch via mirroring) and the share
    /// card, so none of them can drift apart. Greeting wins, then the user's
    /// own intention on the 7th, 14th and 21st, then the affirmation.
    static func dailyLine(for date: Date, greetingDue: Bool, intention: String) -> String {
        if greetingDue {
            return String(localized: "greeting.ritual", defaultValue: "White Rabbits, White Rabbits!")
        }
        let day = Calendar.current.component(.day, from: date)
        if day == 7 || day == 14 || day == 21, !intention.isEmpty {
            return intention
        }
        return line(for: date)
    }

